const text = (value: string): RichNode => ({ type: "text", text: value });
const p = (value: string): RichNode => ({
  type: "paragraph",
  content: [text(value)],
});
const h = (value: string, level = 2): RichNode => ({
  type: "heading",
  attrs: { level },
  content: [text(value)],
});
const code = (language: string, value: string): RichNode => ({
  type: "codeBlock",
  attrs: { language },
  content: [text(value)],
});
const list = (...items: string[]): RichNode => ({
  type: "bulletList",
  content: items.map((item) => ({ type: "listItem", content: [p(item)] })),
});
const quote = (value: string): RichNode => ({
  type: "blockquote",
  content: [p(value)],
});
const table = (rows: string[][]): RichNode => ({
  type: "table",
  content: rows.map((row, i) => ({
    type: "tableRow",
    content: row.map((cell) => ({
      type: i === 0 ? "tableHeader" : "tableCell",
      content: [p(cell)],
    })),
  })),
});
