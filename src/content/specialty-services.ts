export function specialtyDocument(service: SpecialtyService): RichNode {
  const text = (value: string): RichNode => ({ type: "text", text: value });
  return {
    type: "doc",
    content: service.sections.flatMap((section): RichNode[] => [
      { type: "heading", attrs: { level: 2 }, content: [text(section.title)] },
      ...section.paragraphs.map((value): RichNode => ({
        type: "paragraph",
        content: [text(value)],
      })),
      ...(section.items
        ? [
            {
              type: "bulletList",
              content: section.items.map((value): RichNode => ({
                type: "listItem",
                content: [{ type: "paragraph", content: [text(value)] }],
              })),
            },
          ]
        : []),
    ]),
  };
}
